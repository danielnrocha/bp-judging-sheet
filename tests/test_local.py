import pathlib
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).resolve().parent.parent
P=(ROOT/'index.html').as_uri()
with sync_playwright() as pw:
    b=pw.chromium.launch()
    ctx=b.new_context(viewport={'width':1300,'height':900},accept_downloads=True)
    pg=ctx.new_page();errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    ctx.route('**/supabase.min.js',lambda r:r.fulfill(body='',content_type='application/javascript'))
    pg.goto(P);pg.wait_for_timeout(600)
    print('who:',pg.inner_text('#who'),'logout hidden:',pg.is_hidden('#logout'))
    pg.click('[data-act=newT]');pg.fill('#fName','Torneio Teste');pg.click('[data-act=saveT]');pg.wait_for_timeout(400)
